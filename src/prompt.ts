/**
 * ヒント段階の名前。ここが唯一の定義元で、
 * プロンプト・ログ解析・復習ノートはすべてこれを参照する。
 * 変更するときは logger.ts の extractLevel が拾える形か確認すること。
 */
export const LEVEL_NAMES: Record<number, string> = {
  1: "問いの整理",
  2: "方針",
  3: "組み立て",
  4: "部分コード",
};

/** 応答の冒頭に置く段階の印。この表記がそのままログ解析の手がかりになる */
export function levelTag(level: number): string {
  const name = LEVEL_NAMES[level];
  return name ? `[ヒント${level}｜${name}]` : `[ヒント${level}]`;
}

